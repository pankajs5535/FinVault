
using FinVault.Application.Interface.IRepositories;
using FinVault.Domain.Entities;
using FinVault.Persistence.Data;
using Microsoft.EntityFrameworkCore;

namespace FinVault.Persistence.Repositories
{
    public class PaymentGatewayLogRepository : GenericRepository<PaymentGatewayLog>, IPaymentGatewayLogRepository
    {
        public PaymentGatewayLogRepository(FinVaultDbContext context) : base(context)
        {
        }

        // =========================================================
        // 1. LOG IDENTIFICATION
        // =========================================================

        // Retrieves a gateway log using its primary key.
        // Useful for investigating a specific gateway communication attempt.
        public async Task<PaymentGatewayLog?> GetLogDetailsAsync(int paymentGatewayLogId)
        {
            return await _dbSet
                .Include(x => x.PaymentRequest)
                .FirstOrDefaultAsync(x => x.PaymentGatewayLogId == paymentGatewayLogId);
        }

        // Retrieves gateway logs using their correlation identifier.
        // Useful for tracing related gateway calls across a payment processing workflow.
        public async Task<IEnumerable<PaymentGatewayLog>> GetByCorrelationIdAsync(string correlationId)
        {
            return await _dbSet
                .Where(x => x.CorrelationId == correlationId)
                .OrderBy(x => x.CreatedAt)
                .ToListAsync();
        }

        // Retrieves the latest gateway log for a payment request.
        // Useful for checking the most recent gateway response before deciding the next processing step.
        public async Task<PaymentGatewayLog?> GetLatestLogByPaymentRequestIdAsync(int paymentRequestId)
        {
            return await _dbSet
                .Where(x => x.PaymentRequestId == paymentRequestId)
                .OrderByDescending(x => x.CreatedAt)
                .ThenByDescending(x => x.PaymentGatewayLogId)
                .FirstOrDefaultAsync();
        }

        // Retrieves a specific attempt for a payment request.
        // Useful for investigating an individual retry or gateway communication attempt.
        public async Task<PaymentGatewayLog?> GetByPaymentRequestAndAttemptAsync(int paymentRequestId, int attemptNumber)
        {
            return await _dbSet
                .Where(x => x.PaymentRequestId == paymentRequestId && x.AttemptNumber == attemptNumber)
                .OrderByDescending(x => x.CreatedAt)
                .FirstOrDefaultAsync();
        }

        // =========================================================
        // 2. PAYMENT REQUEST HISTORY
        // =========================================================

        // Retrieves all gateway logs for a payment request in chronological order.
        // Useful for reconstructing the complete gateway interaction history.
        public async Task<IEnumerable<PaymentGatewayLog>> GetByPaymentRequestIdAsync(int paymentRequestId)
        {
            return await _dbSet
                .Where(x => x.PaymentRequestId == paymentRequestId)
                .OrderBy(x => x.CreatedAt)
                .ThenBy(x => x.PaymentGatewayLogId)
                .ToListAsync();
        }

        // Retrieves gateway logs for a payment request with the related payment request.
        // Useful for investigating gateway responses alongside their originating payment instructions.
        public async Task<IEnumerable<PaymentGatewayLog>> GetLogsWithPaymentRequestAsync(int paymentRequestId)
        {
            return await _dbSet
                .Include(x => x.PaymentRequest)
                .Where(x => x.PaymentRequestId == paymentRequestId)
                .OrderBy(x => x.CreatedAt)
                .ToListAsync();
        }

        // Retrieves gateway logs for multiple payment requests.
        // Useful for investigating gateway activity across a group of payments.
        public async Task<IEnumerable<PaymentGatewayLog>> GetByPaymentRequestIdsAsync(IEnumerable<int> paymentRequestIds)
        {
            var ids = paymentRequestIds.Distinct().ToList();

            return await _dbSet
                .Where(x => ids.Contains(x.PaymentRequestId))
                .OrderBy(x => x.CreatedAt)
                .ToListAsync();
        }

        // =========================================================
        // 3. GATEWAY AND OPERATION TRACKING
        // =========================================================

        // Retrieves logs generated by a particular gateway.
        // Useful for monitoring gateway-specific reliability and response behavior.
        public async Task<IEnumerable<PaymentGatewayLog>> GetByGatewayNameAsync(string gatewayName)
        {
            return await _dbSet
                .Where(x => x.GatewayName == gatewayName)
                .OrderByDescending(x => x.CreatedAt)
                .ToListAsync();
        }

        // Retrieves logs for a particular gateway operation.
        // Useful for separating initiation, status checks, callbacks, reversals and refunds.
        public async Task<IEnumerable<PaymentGatewayLog>> GetByOperationAsync(string operation)
        {
            return await _dbSet
                .Where(x => x.Operation == operation)
                .OrderByDescending(x => x.CreatedAt)
                .ToListAsync();
        }

        // Retrieves logs for a gateway and a particular operation.
        // Useful for analyzing a specific operation performed through a gateway.
        public async Task<IEnumerable<PaymentGatewayLog>> GetByGatewayAndOperationAsync(string gatewayName, string operation)
        {
            return await _dbSet
                .Where(x => x.GatewayName == gatewayName && x.Operation == operation)
                .OrderByDescending(x => x.CreatedAt)
                .ToListAsync();
        }

        // =========================================================
        // 4. SUCCESS AND FAILURE MONITORING
        // =========================================================

        // Retrieves successful gateway communication logs.
        // Useful for monitoring successful gateway interactions.
        public async Task<IEnumerable<PaymentGatewayLog>> GetSuccessfulLogsAsync()
        {
            return await _dbSet
                .Where(x => x.IsSuccess)
                .OrderByDescending(x => x.CreatedAt)
                .ToListAsync();
        }

        // Retrieves failed gateway communication logs.
        // Useful for investigating gateway errors and unsuccessful responses.
        public async Task<IEnumerable<PaymentGatewayLog>> GetFailedLogsAsync()
        {
            return await _dbSet
                .Where(x => !x.IsSuccess)
                .OrderByDescending(x => x.CreatedAt)
                .ToListAsync();
        }

        // Retrieves failed gateway logs for a payment request.
        // Useful for reviewing all failed attempts associated with one payment.
        public async Task<IEnumerable<PaymentGatewayLog>> GetFailedLogsByPaymentRequestIdAsync(int paymentRequestId)
        {
            return await _dbSet
                .Where(x => x.PaymentRequestId == paymentRequestId && !x.IsSuccess)
                .OrderBy(x => x.CreatedAt)
                .ToListAsync();
        }

        // Retrieves logs matching a gateway response code.
        // Useful for grouping and investigating recurring gateway response errors.
        public async Task<IEnumerable<PaymentGatewayLog>> GetByResponseCodeAsync(string responseCode)
        {
            return await _dbSet
                .Where(x => x.ResponseCode == responseCode)
                .OrderByDescending(x => x.CreatedAt)
                .ToListAsync();
        }

        // Retrieves logs matching an HTTP status code.
        // Useful for analyzing HTTP-level gateway communication failures.
        public async Task<IEnumerable<PaymentGatewayLog>> GetByHttpStatusCodeAsync(int httpStatusCode)
        {
            return await _dbSet
                .Where(x => x.HttpStatusCode == httpStatusCode)
                .OrderByDescending(x => x.CreatedAt)
                .ToListAsync();
        }

        // =========================================================
        // 5. DATE-BASED MONITORING
        // =========================================================

        // Retrieves gateway logs created within the supplied date range.
        // Useful for monitoring gateway activity over a reporting period.
        public async Task<IEnumerable<PaymentGatewayLog>> GetLogsWithinRangeAsync(DateTime startDate, DateTime endDate)
        {
            return await _dbSet
                .Where(x => x.CreatedAt >= startDate && x.CreatedAt <= endDate)
                .OrderByDescending(x => x.CreatedAt)
                .ToListAsync();
        }

        // Retrieves failed gateway logs created within the supplied date range.
        // Useful for analyzing gateway failures during a particular operational period.
        public async Task<IEnumerable<PaymentGatewayLog>> GetFailedLogsWithinRangeAsync(DateTime startDate, DateTime endDate)
        {
            return await _dbSet
                .Where(x => !x.IsSuccess && x.CreatedAt >= startDate && x.CreatedAt <= endDate)
                .OrderByDescending(x => x.CreatedAt)
                .ToListAsync();
        }

        // =========================================================
        // 6. PERFORMANCE AND RETRY ANALYSIS
        // =========================================================

        // Retrieves gateway logs whose response duration exceeds the supplied threshold.
        // Useful for identifying slow gateway responses and potential performance issues.
        public async Task<IEnumerable<PaymentGatewayLog>> GetSlowGatewayLogsAsync(int minimumDurationMs)
        {
            return await _dbSet
                .Where(x => x.DurationMs.HasValue && x.DurationMs.Value > minimumDurationMs)
                .OrderByDescending(x => x.DurationMs)
                .ToListAsync();
        }

        // Calculates the average recorded gateway response duration.
        // Useful for monitoring gateway response performance over a reporting period.
        public async Task<double?> GetAverageDurationWithinRangeAsync(DateTime startDate, DateTime endDate)
        {
            return await _dbSet
                .Where(x => x.DurationMs.HasValue && x.CreatedAt >= startDate && x.CreatedAt <= endDate)
                .AverageAsync(x => (double?)x.DurationMs);
        }

        // Retrieves the highest recorded attempt number for a payment request.
        // Useful for reviewing retry history and enforcing retry limits in the payment service.
        public async Task<int> GetMaximumAttemptNumberAsync(int paymentRequestId)
        {
            return await _dbSet
                .Where(x => x.PaymentRequestId == paymentRequestId)
                .Select(x => (int?)x.AttemptNumber)
                .MaxAsync() ?? 0;
        }

        // =========================================================
        // 7. SEARCH AND COUNTS
        // =========================================================

        // Searches gateway logs by gateway, correlation ID, response code or error message.
        // Useful for locating technical failures during payment investigations.
        public async Task<IEnumerable<PaymentGatewayLog>> SearchGatewayLogsAsync(string searchTerm)
        {
            return await _dbSet
                .Where(x => x.GatewayName.Contains(searchTerm) ||
                            x.CorrelationId.Contains(searchTerm) ||
                            (x.ResponseCode != null && x.ResponseCode.Contains(searchTerm)) ||
                            (x.ResponseMessage != null && x.ResponseMessage.Contains(searchTerm)) ||
                            (x.ErrorMessage != null && x.ErrorMessage.Contains(searchTerm)))
                .OrderByDescending(x => x.CreatedAt)
                .ToListAsync();
        }

        // Counts gateway logs for a payment request.
        // Useful for monitoring the number of gateway interactions associated with a payment.
        public async Task<int> CountLogsByPaymentRequestIdAsync(int paymentRequestId)
        {
            return await _dbSet.CountAsync(x => x.PaymentRequestId == paymentRequestId);
        }

        // Counts failed gateway logs for a particular gateway.
        // Useful for monitoring gateway reliability and failure volumes.
        public async Task<int> CountFailedLogsByGatewayAsync(string gatewayName)
        {
            return await _dbSet.CountAsync(x => x.GatewayName == gatewayName && !x.IsSuccess);
        }
    }
}
