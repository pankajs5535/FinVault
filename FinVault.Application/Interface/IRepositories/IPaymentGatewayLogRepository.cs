
using FinVault.Domain.Entities;

namespace FinVault.Application.Interface.IRepositories
{
    public interface IPaymentGatewayLogRepository : IGenericRepository<PaymentGatewayLog>
    {
        // =========================================================
        // 1. LOG IDENTIFICATION
        // =========================================================

        // Retrieves a gateway log using its primary key.
        // Useful for investigating a specific gateway communication attempt.
        Task<PaymentGatewayLog?> GetLogDetailsAsync(int paymentGatewayLogId);

        // Retrieves gateway logs using their correlation identifier.
        // Useful for tracing related gateway calls across a payment processing workflow.
        Task<IEnumerable<PaymentGatewayLog>> GetByCorrelationIdAsync(string correlationId);

        // Retrieves the latest gateway log for a payment request.
        // Useful for checking the most recent gateway response before deciding the next processing step.
        Task<PaymentGatewayLog?> GetLatestLogByPaymentRequestIdAsync(int paymentRequestId);

        // Retrieves a specific attempt for a payment request.
        // Useful for investigating an individual retry or gateway communication attempt.
        Task<PaymentGatewayLog?> GetByPaymentRequestAndAttemptAsync(int paymentRequestId, int attemptNumber);

        // =========================================================
        // 2. PAYMENT REQUEST HISTORY
        // =========================================================

        // Retrieves all gateway logs for a payment request in chronological order.
        // Useful for reconstructing the complete gateway interaction history.
        Task<IEnumerable<PaymentGatewayLog>> GetByPaymentRequestIdAsync(int paymentRequestId);

        // Retrieves gateway logs for a payment request with the related payment request.
        // Useful for investigating gateway responses alongside their originating payment instructions.
        Task<IEnumerable<PaymentGatewayLog>> GetLogsWithPaymentRequestAsync(int paymentRequestId);

        // Retrieves gateway logs for multiple payment requests.
        // Useful for investigating gateway activity across a group of payments.
        Task<IEnumerable<PaymentGatewayLog>> GetByPaymentRequestIdsAsync(IEnumerable<int> paymentRequestIds);

        // =========================================================
        // 3. GATEWAY AND OPERATION TRACKING
        // =========================================================

        // Retrieves logs generated by a particular gateway.
        // Useful for monitoring gateway-specific reliability and response behavior.
        Task<IEnumerable<PaymentGatewayLog>> GetByGatewayNameAsync(string gatewayName);

        // Retrieves logs for a particular gateway operation.
        // Useful for separating initiation, status checks, callbacks, reversals and refunds.
        Task<IEnumerable<PaymentGatewayLog>> GetByOperationAsync(string operation);

        // Retrieves logs for a gateway and a particular operation.
        // Useful for analyzing a specific operation performed through a gateway.
        Task<IEnumerable<PaymentGatewayLog>> GetByGatewayAndOperationAsync(string gatewayName, string operation);

        // =========================================================
        // 4. SUCCESS AND FAILURE MONITORING
        // =========================================================

        // Retrieves successful gateway communication logs.
        // Useful for monitoring successful gateway interactions.
        Task<IEnumerable<PaymentGatewayLog>> GetSuccessfulLogsAsync();

        // Retrieves failed gateway communication logs.
        // Useful for investigating gateway errors and unsuccessful responses.
        Task<IEnumerable<PaymentGatewayLog>> GetFailedLogsAsync();

        // Retrieves failed gateway logs for a payment request.
        // Useful for reviewing all failed attempts associated with one payment.
        Task<IEnumerable<PaymentGatewayLog>> GetFailedLogsByPaymentRequestIdAsync(int paymentRequestId);

        // Retrieves logs matching a gateway response code.
        // Useful for grouping and investigating recurring gateway response errors.
        Task<IEnumerable<PaymentGatewayLog>> GetByResponseCodeAsync(string responseCode);

        // Retrieves logs matching an HTTP status code.
        // Useful for analyzing HTTP-level gateway communication failures.
        Task<IEnumerable<PaymentGatewayLog>> GetByHttpStatusCodeAsync(int httpStatusCode);

        // =========================================================
        // 5. DATE-BASED MONITORING
        // =========================================================

        // Retrieves gateway logs created within the supplied date range.
        // Useful for monitoring gateway activity over a reporting period.
        Task<IEnumerable<PaymentGatewayLog>> GetLogsWithinRangeAsync(DateTime startDate, DateTime endDate);

        // Retrieves failed gateway logs created within the supplied date range.
        // Useful for analyzing gateway failures during a particular operational period.
        Task<IEnumerable<PaymentGatewayLog>> GetFailedLogsWithinRangeAsync(DateTime startDate, DateTime endDate);

        // =========================================================
        // 6. PERFORMANCE AND RETRY ANALYSIS
        // =========================================================

        // Retrieves gateway logs whose response duration exceeds the supplied threshold.
        // Useful for identifying slow gateway responses and potential performance issues.
        Task<IEnumerable<PaymentGatewayLog>> GetSlowGatewayLogsAsync(int minimumDurationMs);

        // Calculates the average recorded gateway response duration.
        // Useful for monitoring gateway response performance over a reporting period.
        Task<double?> GetAverageDurationWithinRangeAsync(DateTime startDate, DateTime endDate);

        // Retrieves the highest recorded attempt number for a payment request.
        // Useful for reviewing retry history and enforcing retry limits in the payment service.
        Task<int> GetMaximumAttemptNumberAsync(int paymentRequestId);

        // =========================================================
        // 7. SEARCH AND COUNTS
        // =========================================================

        // Searches gateway logs by gateway, correlation ID, response code or error message.
        // Useful for locating technical failures during payment investigations.
        Task<IEnumerable<PaymentGatewayLog>> SearchGatewayLogsAsync(string searchTerm);

        // Counts gateway logs for a payment request.
        // Useful for monitoring the number of gateway interactions associated with a payment.
        Task<int> CountLogsByPaymentRequestIdAsync(int paymentRequestId);

        // Counts failed gateway logs for a particular gateway.
        // Useful for monitoring gateway reliability and failure volumes.
        Task<int> CountFailedLogsByGatewayAsync(string gatewayName);
    }
}
